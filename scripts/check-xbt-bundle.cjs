// Check the security overlay against its source lock and Docker build input.
const crypto = require('node:crypto')
const lock = JSON.parse(fs.readFileSync('assets/xbt/source-lock.json', 'utf8'))
const overlay = fs.readFileSync('assets/xbt/cln-26.06.9-security.patch')
const digest = crypto.createHash('sha256').update(overlay).digest('hex')
assert.equal(digest, lock.security_overlay.patch_sha256)
assert.equal(lock.security_overlay.release, 'v26.06.9')
const dockerfile = fs.readFileSync('Dockerfile.xbt', 'utf8')
assert.ok(dockerfile.includes(digest))
assert.ok(dockerfile.includes('git apply --check /tmp/cln-26.06.9-security.patch'))
assert.ok(dockerfile.includes(lock.security_overlay.binary_version))
console.log('XBT security overlay digest, release and build binding OK')

